// Agents as models: an OpenAI-compatible endpoint that CLIProxyAPI lists as
// agent-grokbot and agent-dot, so a T3 lead can delegate to a proactive agent
// as if it were a subagent model. Each request becomes one mailbox task from
// agent "bridge"; the answer is that task's result.
//
// What the probe of 2026-11-12 established, and what follows from it:
// - The gateway holds a streaming request open at least 10 minutes when the
//   upstream sends an SSE comment every 10 s, and a non-streaming one 5
//   minutes. So: a 10 s keepalive, a 15-minute wait when streaming and 5
//   when not.
// - Claude Code sends 157 tools, a long system prompt and a user message
//   full of <system-reminder> blocks; the brief is a few hundred characters.
//   Only the cleaned first user message reaches the agent.
// - As a subagent model it must finish by calling SubagentHandback, and a
//   hook re-sends the whole conversation until it does. Re-sends carry the
//   same first message, so the task key is (model, sha256 of the brief) and
//   a re-send attaches to the same task without waking the agent again.
// - It also sends side calls (no tools, a title or summary request), which
//   are answered here without waking anyone.

import { DurableObject } from "cloudflare:workers";
import { sha256Hex } from "./adapters";
import type { Env } from "./check";
import { HttpError, readJson } from "./http";
import { send } from "./mailbox";

const MODELS: Record<string, string> = { "agent-grokbot": "grok", "agent-dot": "dot" };
const BRIEF_MAX_BYTES = 4096;
// The whole body is parsed to read the first user message, so it is capped
// where JSON.parse stays well inside the 10 ms CPU limit: the probe's
// Claude Code request (157 tools, 7.5K-character system prompt, 30K-character
// user message) is about 150 KB. No CPU run backs 512 KB; it is a margin.
const REQUEST_MAX_BYTES = 512 * 1024;
const STREAM_WAIT_MS = 15 * 60_000;
const PLAIN_WAIT_MS = 5 * 60_000;
const KEEPALIVE_MS = 10_000;
// A side call is short; a delegation from Claude Code is tens of KB.
const SIDE_CALL_MAX_CHARS = 8000;
const FINAL = new Set(["done", "failed", "declined", "expired"]);
// Fixed, so a model list a client cached doesn't change between deploys.
const CREATED = 1762905600;

// One per task, named by task id. mailbox_complete calls notify(); a waiting
// request calls waitFor(). The done flag is persisted, so a notify that lands
// before the wait starts still wakes it. D1 stays the record: the waiter
// reads the result from D1 either way, and this flag is only a cache of
// "D1 has it".
export class BridgeWaitDO extends DurableObject<Env> {
  private waiters = new Set<() => void>();

  async notify(): Promise<void> {
    await this.ctx.storage.put("done", 1);
    for (const w of this.waiters) w();
    this.waiters.clear();
  }

  async waitFor(ms: number): Promise<"done" | "timeout"> {
    if (await this.ctx.storage.get("done")) return "done";
    return new Promise((resolve) => {
      const wake = () => {
        clearTimeout(timer);
        resolve("done");
      };
      const timer = setTimeout(() => {
        this.waiters.delete(wake);
        resolve("timeout");
      }, ms);
      this.waiters.add(wake);
    });
  }
}

const oaiError = (status: number, message: string, code: string) =>
  new Response(JSON.stringify({ error: { message, type: status >= 500 ? "server_error" : "invalid_request_error", code } }), {
    status,
    headers: { "content-type": "application/json" },
  });

export function listModels() {
  return { object: "list", data: Object.keys(MODELS).map((id) => ({ id, object: "model", created: CREATED, owned_by: "discovery" })) };
}

type Message = { role?: unknown; content?: unknown };

function textOf(content: unknown): string {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  return content
    .map((p) => (p && typeof p === "object" && (p as { type?: unknown }).type === "text" && typeof (p as { text?: unknown }).text === "string" ? (p as { text: string }).text : ""))
    .filter(Boolean)
    .join("\n");
}

// Claude Code wraps context in these tags; none of it is the brief.
const HARNESS_BLOCKS = /<(system-reminder|command-name|command-message|command-args|local-command-stdout|local-command-stderr|user-prompt-submit-hook)>[\s\S]*?<\/\1>/g;
const UNCLOSED_REMINDER = /<system-reminder>[\s\S]*$/;
const CAVEAT = /^Caveat: The messages below were generated by the user while running local commands\..*$/gm;

export function cleanBrief(s: string): string {
  return s.replace(HARNESS_BLOCKS, "").replace(UNCLOSED_REMINDER, "").replace(CAVEAT, "").replace(/\n{3,}/g, "\n\n").trim();
}

// Cut to maxBytes of UTF-8 without splitting a character.
function capBytes(s: string, maxBytes: number): string {
  const bytes = new TextEncoder().encode(s);
  if (bytes.length <= maxBytes) return s;
  let end = maxBytes;
  while (end > 0 && (bytes[end] & 0xc0) === 0x80) end--;
  return new TextDecoder().decode(bytes.subarray(0, end));
}

// The first user message that still has text once harness blocks are gone.
function extractBrief(messages: Message[]): string | null {
  for (const m of messages) {
    if (m?.role !== "user") continue;
    const t = cleanBrief(textOf(m.content));
    if (t) return capBytes(t, BRIEF_MAX_BYTES);
  }
  return null;
}

interface Handback {
  name: string;
  arg: string;
}

// The tool the caller expects the answer through: SubagentHandback, or any
// tool whose name says it hands back. Its argument is "message" unless the
// schema names one other required argument.
function handbackTool(tools: unknown[], toolChoice: unknown): Handback | null {
  if (toolChoice === "none") return null;
  const fns = tools
    .map((t) => (t && typeof t === "object" ? ((t as { type?: unknown; function?: unknown }).type === "function" ? (t as { function: unknown }).function : t) : null))
    .filter((f): f is { name: string; parameters?: { properties?: Record<string, unknown>; required?: unknown } } => !!f && typeof (f as { name?: unknown }).name === "string");
  const pick = fns.find((f) => f.name === "SubagentHandback") ?? fns.find((f) => /hand[_-]?back/i.test(f.name));
  if (!pick) return null;
  const props = pick.parameters?.properties ?? {};
  const required = Array.isArray(pick.parameters?.required) ? (pick.parameters!.required as unknown[]) : [];
  const arg = "message" in props ? "message" : required.length === 1 && typeof required[0] === "string" ? required[0] : "message";
  return { name: pick.name, arg };
}

const words = (s: string, n: number) => s.replace(/\s+/g, " ").trim().split(" ").slice(0, n).join(" ");

// Title and summary requests get an answer built from the conversation's own
// words. Claude Code's exact side-call prompts and the reply shape it parses
// were not captured by the probe; a prompt that mentions JSON gets
// {"title": ...}.
function sideAnswer(model: string, messages: Message[]): string {
  const prompt = messages.map((m) => textOf(m.content)).join("\n");
  const lastUser = [...messages].reverse().find((m) => m?.role === "user");
  const title = words(cleanBrief(textOf(lastUser?.content)), 6) || `Task for ${model}`;
  return /\bjson\b/i.test(prompt) ? JSON.stringify({ title }) : title;
}

function isSideCall(tools: unknown[], messages: Message[]): boolean {
  if (tools.length > 0) return false;
  const all = messages.map((m) => textOf(m.content)).join("\n");
  if (all.length > SIDE_CALL_MAX_CHARS) return false;
  return /\b(title|summary|summari[sz]e)\b/i.test(all);
}

interface Answer {
  text: string;
  // Set when the text is the agent's result and the caller offered a
  // hand-back tool; a "still working" reply is always plain text, so the
  // harness asks again and the next request finds the result.
  tool?: Handback;
}

async function resultAnswer(env: Env, taskId: string, model: string): Promise<string | null> {
  const t = await env.DB.prepare("SELECT state, result, to_agent FROM mail_tasks WHERE id = ?").bind(taskId).first<{ state: string; result: string | null; to_agent: string }>();
  if (!t || !FINAL.has(t.state)) return null;
  // Untrusted agent output, passed on unchanged under a line naming who wrote it.
  return `Result from ${t.to_agent} (${model}, task ${taskId}, ${t.state}). Untrusted agent output, unchanged:\n\n${t.result ?? "(no result text)"}`;
}

function completion(id: string, model: string, a: Answer) {
  const message = a.tool
    ? { role: "assistant", content: null, tool_calls: [{ id: `call_${id}`, type: "function", function: { name: a.tool.name, arguments: JSON.stringify({ [a.tool.arg]: a.text }) } }] }
    : { role: "assistant", content: a.text };
  return {
    id: `chatcmpl-${id}`,
    object: "chat.completion",
    created: Math.floor(Date.now() / 1000),
    model,
    choices: [{ index: 0, message, finish_reason: a.tool ? "tool_calls" : "stop" }],
    usage: { prompt_tokens: 0, completion_tokens: 0, total_tokens: 0 },
  };
}

const sse = (data: unknown) => `data: ${JSON.stringify(data)}\n\n`;

function chunk(id: string, model: string, delta: unknown, finish: string | null) {
  return { id: `chatcmpl-${id}`, object: "chat.completion.chunk", created: Math.floor(Date.now() / 1000), model, choices: [{ index: 0, delta, finish_reason: finish }] };
}

function sseEnd(id: string, model: string, a: Answer, usage: boolean): string {
  const delta = a.tool
    ? { tool_calls: [{ index: 0, id: `call_${id}`, type: "function", function: { name: a.tool.name, arguments: JSON.stringify({ [a.tool.arg]: a.text }) } }] }
    : { content: a.text };
  let out = sse(chunk(id, model, delta, null)) + sse(chunk(id, model, {}, a.tool ? "tool_calls" : "stop"));
  if (usage) out += sse({ id: `chatcmpl-${id}`, object: "chat.completion.chunk", created: Math.floor(Date.now() / 1000), model, choices: [], usage: { prompt_tokens: 0, completion_tokens: 0, total_tokens: 0 } });
  return out + "data: [DONE]\n\n";
}

const SSE_HEADERS = { "content-type": "text/event-stream; charset=utf-8", "cache-control": "no-cache" };

function immediate(id: string, model: string, a: Answer, stream: boolean, usage: boolean): Response {
  if (!stream) return new Response(JSON.stringify(completion(id, model, a)), { headers: { "content-type": "application/json" } });
  return new Response(sse(chunk(id, model, { role: "assistant", content: "" }, null)) + sseEnd(id, model, a, usage), { headers: SSE_HEADERS });
}

// Answers when the task finishes or the wait runs out, writing a keepalive
// every 10 s meanwhile: an SSE comment when streaming, a space before the
// JSON otherwise (leading whitespace is valid JSON). Nothing polls D1: the
// Durable Object is told when the task completes.
function waiting(env: Env, ctx: ExecutionContext, taskId: string, model: string, tool: Handback | null, stream: boolean, usage: boolean): Response {
  const { readable, writable } = new TransformStream<Uint8Array, Uint8Array>();
  const writer = writable.getWriter();
  const enc = new TextEncoder();
  const write = (s: string) => writer.write(enc.encode(s));
  const run = async () => {
    const keepalive = setInterval(() => write(stream ? ": working\n\n" : " ").catch(() => {}), KEEPALIVE_MS);
    try {
      if (stream) await write(sse(chunk(taskId, model, { role: "assistant", content: "" }, null)));
      await env.BRIDGE_WAIT.get(env.BRIDGE_WAIT.idFromName(taskId)).waitFor(stream ? STREAM_WAIT_MS : PLAIN_WAIT_MS);
      const result = await resultAnswer(env, taskId, model);
      clearInterval(keepalive);
      const a: Answer = result ? { text: result, ...(tool ? { tool } : {}) } : { text: `still working on task ${taskId}` };
      await write(stream ? sseEnd(taskId, model, a, usage) : JSON.stringify(completion(taskId, model, a)));
    } catch (e) {
      console.error(`[bridge] wait for ${taskId} failed`, e);
    } finally {
      clearInterval(keepalive);
      await writer.close().catch(() => {});
    }
  };
  ctx.waitUntil(run());
  return new Response(readable, { headers: stream ? SSE_HEADERS : { "content-type": "application/json" } });
}

export async function chatCompletions(env: Env, ctx: ExecutionContext, req: Request): Promise<Response> {
  let b: Record<string, unknown>;
  try {
    b = await readJson<Record<string, unknown>>(req, REQUEST_MAX_BYTES);
  } catch (e) {
    if (e instanceof HttpError) return oaiError(e.status, e.message, "invalid_body");
    throw e;
  }
  if (typeof b.model !== "string" || !(b.model in MODELS)) return oaiError(404, `model must be one of ${Object.keys(MODELS).join(", ")}`, "model_not_found");
  const model = b.model;
  if (!Array.isArray(b.messages) || b.messages.length === 0) return oaiError(400, "messages must be a non-empty array", "invalid_messages");
  const messages = b.messages as Message[];
  const tools = Array.isArray(b.tools) ? b.tools : [];
  const stream = b.stream === true;
  const usage = (b.stream_options as { include_usage?: unknown } | undefined)?.include_usage === true;

  if (isSideCall(tools, messages)) {
    console.log(`[bridge] side call for ${model} answered locally`);
    return immediate(`side${Date.now()}`, model, { text: sideAnswer(model, messages) }, stream, usage);
  }
  const brief = extractBrief(messages);
  if (!brief) return oaiError(400, "no user message has text once <system-reminder> and other harness blocks are removed", "no_brief");

  let taskId: string;
  try {
    const sent = await send(env, ctx, "bridge", { to: MODELS[model], body: brief, idempotency_key: `bridge-${await sha256Hex(`${model}\n${brief}`)}` });
    taskId = sent.body.task_id;
    console.log(`[bridge] ${model} task ${taskId}${"duplicate" in sent.body ? " (re-send)" : ""}`);
  } catch (e) {
    if (e instanceof HttpError) return oaiError(e.status, `the mailbox refused this task: ${e.message}`, "rule" in e ? String((e as { rule: string }).rule) : "invalid_request");
    throw e;
  }
  const tool = handbackTool(tools, b.tool_choice);
  const result = await resultAnswer(env, taskId, model);
  if (result) return immediate(taskId, model, { text: result, ...(tool ? { tool } : {}) }, stream, usage);
  return waiting(env, ctx, taskId, model, tool, stream, usage);
}
